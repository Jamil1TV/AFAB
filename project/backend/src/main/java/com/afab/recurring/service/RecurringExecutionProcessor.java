package com.afab.recurring.service;

import com.afab.business.Business;
import com.afab.finance.domain.Transaction;
import com.afab.finance.repository.TransactionRepository;
import com.afab.finance.service.TransactionService;
import com.afab.recurring.domain.RecurringTransaction;
import com.afab.recurring.domain.RecurringTransactionExecution;
import com.afab.recurring.repository.RecurringTransactionExecutionRepository;
import com.afab.recurring.repository.RecurringTransactionRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.time.LocalDate;
import java.util.Optional;
import java.util.UUID;

/**
 * Isolated transactional processor for a single recurring transaction occurrence.
 * Uses REQUIRES_NEW so one business's failure cannot roll back other businesses' schedules,
 * combined with a pessimistic row lock + DB UNIQUE (recurring_transaction_id, scheduled_date)
 * for strict idempotency under multi-instance deployments.
 */
@Service
public class RecurringExecutionProcessor {

    private static final Logger log = LoggerFactory.getLogger(RecurringExecutionProcessor.class);

    private final RecurringTransactionRepository recurringRepository;
    private final RecurringTransactionExecutionRepository executionRepository;
    private final TransactionRepository transactionRepository;
    private final TransactionService transactionService;

    public RecurringExecutionProcessor(
            RecurringTransactionRepository recurringRepository,
            RecurringTransactionExecutionRepository executionRepository,
            TransactionRepository transactionRepository,
            TransactionService transactionService
    ) {
        this.recurringRepository = recurringRepository;
        this.executionRepository = executionRepository;
        this.transactionRepository = transactionRepository;
        this.transactionService = transactionService;
    }

    @Transactional(propagation = Propagation.REQUIRES_NEW)
    public Optional<UUID> executeSingleDueOccurrence(UUID ruleId, LocalDate businessToday) {
        Optional<RecurringTransaction> maybeRule = recurringRepository.findByIdForUpdate(ruleId);
        if (maybeRule.isEmpty()) {
            return Optional.empty();
        }

        RecurringTransaction rule = maybeRule.get();
        Business business = rule.getBusiness();
        if (!rule.isActive() || business == null || business.getArchivedAt() != null || !business.isEditable()) {
            return Optional.empty();
        }

        LocalDate scheduledDate = rule.getNextExecutionDate();
        if (scheduledDate == null || scheduledDate.isAfter(businessToday)) {
            return Optional.empty();
        }

        // If scheduled date has passed endDate, auto-deactivate without creating a transaction
        if (rule.getEndDate() != null && scheduledDate.isAfter(rule.getEndDate())) {
            rule.setActive(false);
            recurringRepository.save(rule);
            return Optional.empty();
        }

        // Idempotency check: never create duplicate transaction for the same (rule, scheduledDate)
        if (executionRepository.existsByRecurringTransactionIdAndScheduledDate(rule.getId(), scheduledDate)) {
            advanceRuleSchedule(rule, scheduledDate, false);
            recurringRepository.save(rule);
            log.info("Skipped already-executed recurring occurrence ruleId={} scheduledDate={}", rule.getId(), scheduledDate);
            return Optional.empty();
        }

        // Build and persist the generated Transaction with immutable FX snapshot at execution time
        Transaction tx = new Transaction();
        tx.setBusiness(business);
        tx.setType(rule.getType());
        transactionService.applyFxSnapshot(tx, business, rule.getAmount(), rule.getCurrency(), null);
        tx.setDescription(rule.getDescription());
        tx.setTransactionDate(scheduledDate);
        tx.setCategory(rule.getCategory());
        tx.setPaymentMethod(rule.getPaymentMethod());
        tx.setStatus("COMPLETED");
        String note = (rule.getNotes() != null && !rule.getNotes().isBlank())
                ? rule.getNotes()
                : "Generated by recurring schedule (" + rule.getFrequency().name() + ")";
        tx.setNotes(note);

        tx = transactionRepository.save(tx);

        // Record execution ledger (enforced unique in DB on (recurring_transaction_id, scheduled_date))
        RecurringTransactionExecution execution = new RecurringTransactionExecution(
                business,
                rule,
                scheduledDate,
                tx
        );
        executionRepository.save(execution);

        // Advance nextExecutionDate and auto-deactivate if past endDate
        advanceRuleSchedule(rule, scheduledDate, true);
        recurringRepository.save(rule);

        log.info("Executed recurring ruleId={} scheduledDate={} transactionId={}",
                rule.getId(), scheduledDate, tx.getId());
        return Optional.of(tx.getId());
    }

    private void advanceRuleSchedule(RecurringTransaction rule, LocalDate executedDate, boolean updateTimestamp) {
        LocalDate nextDate = rule.getFrequency().nextDate(executedDate);
        rule.setNextExecutionDate(nextDate);
        if (updateTimestamp) {
            rule.setLastExecutedAt(Instant.now());
        }
        if (rule.getEndDate() != null && nextDate.isAfter(rule.getEndDate())) {
            rule.setActive(false);
        }
    }
}
