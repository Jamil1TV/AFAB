class PasswordStrengthResult {
  const PasswordStrengthResult({
    required this.hasMinLength,
    required this.hasUppercase,
    required this.hasLowercase,
    required this.hasDigit,
    required this.hasSpecial,
  });

  final bool hasMinLength;
  final bool hasUppercase;
  final bool hasLowercase;
  final bool hasDigit;
  final bool hasSpecial;

  int get score =>
      (hasMinLength ? 1 : 0) +
      (hasUppercase ? 1 : 0) +
      (hasLowercase ? 1 : 0) +
      (hasDigit ? 1 : 0) +
      (hasSpecial ? 1 : 0);

  bool get isStrongEnough => score == 5;
}

abstract final class AppValidators {
  static final RegExp _emailRegex = RegExp(r'^[^\s@]+@[^\s@]+\.[^\s@]+$');

  static bool isValidEmail(String value) => _emailRegex.hasMatch(value.trim());

  static PasswordStrengthResult evaluatePassword(String password) {
    return PasswordStrengthResult(
      hasMinLength: password.length >= 8,
      hasUppercase: RegExp(r'[A-Z]').hasMatch(password),
      hasLowercase: RegExp(r'[a-z]').hasMatch(password),
      hasDigit: RegExp(r'[0-9]').hasMatch(password),
      hasSpecial: RegExp(r'[^A-Za-z0-9]').hasMatch(password),
    );
  }

  /// Preserves underscores (`_`) and hyphens (`-`) used by Base64URL reset tokens
  /// generated by `AuthService.generateSecureToken()`.
  /// Fixes the Web bug in `reset-password/page.tsx` that stripped `_`.
  static String sanitizeResetToken(String raw) {
    final decoded = Uri.decodeComponent(raw).trim();
    return decoded.replaceAll(RegExp(r'[^a-zA-Z0-9_-]'), '');
  }
}
